#!/bin/bash
# DEPLOY-01: Polygon installer for Ubuntu - system Python + APT packages, no venv.
#
#   ./install_polygon.sh                      production channel into ~/polygon
#   ./install_polygon.sh --channel develop --repo-url URL
#                                             test PC (development repository, URL required)
#   ./install_polygon.sh --install-dir DIR    another directory
#   ./install_polygon.sh --autostart          also start Polygon after login (default off)
#   ./install_polygon.sh --desktop-icon       also put an icon on the desktop
#   ./install_polygon.sh --skip-apt           no apt (packages already installed)
#
# Run as the normal user who will run Polygon (sudo is used only for apt).
# Repeatable: an existing checkout is checked (origin, branch, clean tracked
# files) and fast-forwarded by bin/polygon-update; config/polygon.conf is
# created from the example only when missing (chmod 600) and NEVER overwritten;
# log/ and video/ are kept. Real passwords are never needed or asked for.
#
# Exit codes: 0 OK (preflight PASS / warnings), 1 installation stopped,
# 2 usage error, 3 installed but the preflight reports a HARD FAIL.

set -u

# RELEASE-01: the public release repository - its `production` branch is
# generated by deploy/build_production.sh (sanitized, never a merge)
REPO_URL_DEFAULT="https://github.com/bukowski12/polygon.git"
# Verified on Ubuntu 26.04 (resolute): wpctl <- wireplumber, pw-play <- pipewire-bin
# (both default on Ubuntu desktop). pactl (pulseaudio-utils, universe) and aplay
# (alsa-utils) are optional fallbacks of app/system_volume.py / app/audio.py.
APT_PACKAGES=(
    git python3
    python3-pyqt5 python3-pyqt5.qtmultimedia python3-pyqt5.qtsql
    libqt5multimedia5-plugins libqt5sql5-mysql
    python3-opencv python3-ldap3
    wireplumber pipewire-bin
)

usage() {
    sed -n '2,19p' "$0" | sed 's/^# \{0,1\}//'
}

die() { echo "STOP: $*" >&2; exit 1; }
info() { echo "==> $*"; }

normalize_url() { local url="${1%/}"; echo "${url%.git}"; }

desktop_entry() {
    local dir="$1"
    cat <<EOF
[Desktop Entry]
Type=Application
Name=Polygon
Comment=Řídicí aplikace výcvikového polygonu
Exec="$dir/bin/polygon-start"
Path=$dir
Icon=$dir/files/znak-hzs.png
Terminal=false
Categories=Utility;
EOF
}

main() {
    local channel="production" install_dir="$HOME/polygon" repo_url=""
    local autostart=0 desktop_icon=0 skip_apt=0
    while [ "$#" -gt 0 ]; do
        case "$1" in
            --channel) [ "$#" -ge 2 ] || { echo "--channel needs develop|production" >&2; return 2; }
                       channel="$2"; shift 2 ;;
            --install-dir) [ "$#" -ge 2 ] || { echo "--install-dir needs a path" >&2; return 2; }
                           install_dir="$2"; shift 2 ;;
            --repo-url) [ "$#" -ge 2 ] || { echo "--repo-url needs a URL" >&2; return 2; }
                        repo_url="$2"; shift 2 ;;
            --autostart) autostart=1; shift ;;
            --desktop-icon) desktop_icon=1; shift ;;
            --skip-apt) skip_apt=1; shift ;;
            -h|--help) usage; return 0 ;;
            *) echo "unknown argument: $1 (see --help)" >&2; return 2 ;;
        esac
    done
    case "$channel" in
        develop|production) ;;
        *) echo "--channel must be develop or production, not '$channel'" >&2; return 2 ;;
    esac
    if [ -z "$repo_url" ]; then
        # the release repository has no develop branch
        [ "$channel" = "production" ] || { echo "--channel develop needs --repo-url (the development repository)" >&2; return 2; }
        repo_url="$REPO_URL_DEFAULT"
    fi
    [ "$(id -u)" -ne 0 ] || die "run as the normal Polygon user, not root (sudo is used only for apt)"
    install_dir="$(realpath -m -- "$install_dir")"
    info "channel $channel, directory $install_dir, origin $repo_url"

    if [ "$skip_apt" = 0 ]; then
        info "apt update + install: ${APT_PACKAGES[*]}"
        sudo apt-get update || die "apt-get update failed"
        sudo apt-get install -y "${APT_PACKAGES[@]}" || die "apt-get install failed"
    else
        info "apt skipped (--skip-apt)"
    fi
    command -v git >/dev/null || die "git is not installed"

    if [ -d "$install_dir/.git" ]; then
        info "existing checkout - checking it"
        local origin branch
        origin="$(git -C "$install_dir" remote get-url origin 2>/dev/null)" || die "$install_dir has no origin remote"
        [ "$(normalize_url "$origin")" = "$(normalize_url "$repo_url")" ] \
            || die "$install_dir: origin is $origin, expected $repo_url - nothing changed"
        branch="$(git -C "$install_dir" symbolic-ref --quiet --short HEAD)" || die "$install_dir: detached HEAD"
        [ "$branch" = "$channel" ] \
            || die "$install_dir is on branch '$branch', not '$channel' - switch it by hand or choose --channel $branch"
        git -C "$install_dir" diff --quiet && git -C "$install_dir" diff --cached --quiet \
            || die "$install_dir has changed tracked files - nothing changed, commit/stash them first"
        if [ -x "$install_dir/bin/polygon-update" ]; then
            "$install_dir/bin/polygon-update" || true
        fi
    elif [ -e "$install_dir" ] && [ -n "$(ls -A -- "$install_dir" 2>/dev/null)" ]; then
        die "$install_dir exists, is not empty and is not a Polygon checkout"
    else
        info "git clone --single-branch --no-tags --branch $channel"
        # only the channel branch: no other branches, tags or their history on this PC
        git clone --single-branch --no-tags --branch "$channel" -- "$repo_url" "$install_dir" \
            || die "git clone failed (does origin have the branch '$channel'?)"
    fi

    [ -x "$install_dir/bin/polygon-start" ] \
        || die "this version of '$channel' has no bin/polygon-start (DEPLOY-01) yet - nothing more installed"

    mkdir -p "$install_dir/log" "$install_dir/video"
    local config="$install_dir/config/polygon.conf"
    if [ -e "$config" ]; then
        info "config/polygon.conf exists - kept unchanged"
    else
        cp -- "$install_dir/config/polygon.conf.example" "$config" || die "cannot create $config"
        chmod 600 "$config"
        info "config/polygon.conf created from the example (chmod 600) - fill in the real values"
    fi

    local applications="${XDG_DATA_HOME:-$HOME/.local/share}/applications"
    mkdir -p "$applications"
    desktop_entry "$install_dir" > "$applications/polygon.desktop"
    command -v update-desktop-database >/dev/null && update-desktop-database "$applications" 2>/dev/null
    info "menu launcher: $applications/polygon.desktop"
    if [ "$desktop_icon" = 1 ]; then
        local desktop
        desktop="$(xdg-user-dir DESKTOP 2>/dev/null || echo "$HOME/Desktop")"
        mkdir -p "$desktop"
        desktop_entry "$install_dir" > "$desktop/polygon.desktop"
        chmod +x "$desktop/polygon.desktop"
        command -v gio >/dev/null && gio set "$desktop/polygon.desktop" metadata::trusted true 2>/dev/null
        info "desktop icon: $desktop/polygon.desktop"
    fi
    if [ "$autostart" = 1 ]; then
        local autostart_dir="${XDG_CONFIG_HOME:-$HOME/.config}/autostart"
        mkdir -p "$autostart_dir"
        desktop_entry "$install_dir" > "$autostart_dir/polygon.desktop"
        info "autostart after login: $autostart_dir/polygon.desktop"
    fi

    info "preflight"
    "$install_dir/bin/polygon-preflight"
    local rc=$?
    if [ "$rc" -ge 2 ]; then
        echo "Installed, but the preflight reports a HARD FAIL - see above." >&2
        return 3
    fi
    info "done - start Polygon from the menu or: $install_dir/bin/polygon-start"
    return 0
}

main "$@"; exit $?
